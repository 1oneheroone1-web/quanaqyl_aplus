const supportIds = new Set(['g9-03', 'g9-06', 'g10-03', 'g12-09']);
const grouped = new Map<string, PhysicsTheoryModule>();
for (const row of source.resources) {
  const translation = translations[row.id];
  if (!translation) throw new Error(`Missing theory translation: ${row.id}`);
  const [ru, kk, focusRu, focusKk, relatedTopicIds] = translation;
  const focus = L(row.focus, focusRu, focusKk);
  const role = supportIds.has(row.id) ? 'support' : 'primary';
  let chapter = grouped.get(row.module);
  if (role === 'primary') {
    const slug = moduleSlugs[row.id];
    if (!slug || chapter || ![9, 10, 11, 12].includes(row.grade)) throw new Error(`Invalid theory module: ${row.id}`);
    chapter = {
      id: `${row.grade}-${slug}`, grade: row.grade as TheoryGrade, module: row.module,
      topic: L(row.topic, ru, kk), focus, relatedTopicIds: [...relatedTopicIds], resources: [],
    };
    grouped.set(row.module, chapter);
  }
  if (!chapter) throw new Error(`Support resource has no module: ${row.id}`);
  chapter.resources.push({
    id: role === 'primary' ? `${chapter.id}-primary` : `${chapter.id}-support-${row.id}`,
    sourceId: row.id, title: row.title, provider: row.provider, type: row.resourceType,
    url: row.url, role, focus,
  });
}
export const physicsTheoryModules: PhysicsTheoryModule[] = [...grouped.values()];
export const theoryModulesForGrade = (grade: PhysicsGrade) => physicsTheoryModules.filter(module => module.grade === grade);
export const theoryModulesForTopic = (topic: number) => physicsTheoryModules.filter(module => module.relatedTopicIds.includes(topic));
export function defaultPhysicsGrade(level: string): PhysicsGrade {
  const grade = Number(level);
  return physicsGrades.includes(grade as PhysicsGrade) ? grade as PhysicsGrade : 9;
}
/** Resolve an explicitly clicked study-topic link; no answer scoring or automatic recommendations. */
export function theoryEntryForTopic(topic: number, level: string): PhysicsTheoryModule | undefined {
  const matches = theoryModulesForTopic(topic);
  return matches.find(module => module.grade === Number(level)) ?? matches[0];
}
